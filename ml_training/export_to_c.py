#!/usr/bin/env python3
"""
export_to_c.py - Convert the int8 TFLite model into include/fall_model_data.h

The header contains:
  * g_fall_model_tflite[]  - the flatbuffer, 16-byte aligned for TFLite Micro
  * quantization params    - so the firmware can quantize float IMU windows itself
  * window constants       - checked at compile time against config.h
  * two self-test windows  - the firmware runs them at boot to prove the interpreter works
  * evaluation metrics     - as comments, for traceability
"""
from __future__ import annotations

import datetime as dt
import hashlib
import json
import sys
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
MODELS = HERE / "models"
HEADER = HERE.parent / "include" / "fall_model_data.h"


def c_bytes(data: bytes, per_line: int = 16) -> str:
    lines = []
    for i in range(0, len(data), per_line):
        lines.append("  " + ", ".join(f"0x{b:02x}" for b in data[i:i + per_line]) + ",")
    return "\n".join(lines)


def c_int8(arr: np.ndarray, per_line: int = 24) -> str:
    flat = arr.ravel().tolist()
    lines = []
    for i in range(0, len(flat), per_line):
        lines.append("  " + ", ".join(f"{v:4d}" for v in flat[i:i + per_line]) + ",")
    return "\n".join(lines)


def main() -> int:
    tfl_path = MODELS / "fall_cnn_int8.tflite"
    if not tfl_path.exists():
        print(f"[error] {tfl_path} missing - run train_model.py first")
        return 1
    tfl = tfl_path.read_bytes()
    rep = json.loads((MODELS / "metrics.json").read_text())
    q = rep["quant"]
    w = rep["window"]
    st = np.load(MODELS / "selftest.npz")

    def quant(x):
        return np.clip(np.round(x / q["in_scale"] + q["in_zero"]), -128, 127).astype(np.int8)

    m_all = rep["int8"]["all"]
    per_src = "\n".join(
        f" *   {k:<5}: acc={v['accuracy']:.4f} prec={v['precision']:.4f} recall={v['recall']:.4f} "
        f"f1={v['f1']:.4f} (n={v['n']})"
        for k, v in rep["int8"].items() if k != "all")
    sha = hashlib.sha256(tfl).hexdigest()[:16]
    ops = ", ".join(rep.get("ops", [])) or "see train_model.py"

    header = f"""// =============================================================================
// fall_model_data.h  -  AUTO-GENERATED by ml_training/export_to_c.py. DO NOT EDIT.
// Generated : {dt.datetime.now(dt.timezone.utc).strftime('%Y-%m-%d %H:%M UTC')}
// Model     : 1D-CNN fall classifier, full-integer int8, {len(tfl)} bytes, {rep['params']} params
// SHA-256   : {sha}...
// TFLite ops: {ops}
// Dataset   : {', '.join(f'{k}={v}' for k, v in rep['dataset_sources'].items())} windows
// =============================================================================
/*
 * Held-out-subject evaluation of the QUANTIZED model (threshold {rep['threshold']}):
 *   all  : acc={m_all['accuracy']:.4f} prec={m_all['precision']:.4f} recall={m_all['recall']:.4f} f1={m_all['f1']:.4f} (n={m_all['n']})
{per_src}
 * float/int8 decision agreement: {rep['float_int8_agreement']:.4f}
 */
#pragma once
#include <stdint.h>
#include <stddef.h>

// ---- input/output contract ---------------------------------------------------
#define FALL_MODEL_WINDOW_SAMPLES   {w['samples']}
#define FALL_MODEL_CHANNELS         6        // ax, ay, az [g], gx, gy, gz [dps / FALL_MODEL_GYRO_SCALE]
#define FALL_MODEL_SAMPLE_HZ        {w['fs']}
#define FALL_MODEL_IMPACT_INDEX     {w['impact_index']}
#define FALL_MODEL_GYRO_SCALE       {w['gyro_scale']:.1f}f
#define FALL_MODEL_INPUT_SCALE      {q['in_scale']:.9g}f
#define FALL_MODEL_INPUT_ZERO       ({q['in_zero']})
#define FALL_MODEL_OUTPUT_SCALE     {q['out_scale']:.9g}f
#define FALL_MODEL_OUTPUT_ZERO      ({q['out_zero']})
#define FALL_MODEL_THRESHOLD        {rep['threshold']:.3f}f
#define FALL_MODEL_TENSOR_ARENA     (24 * 1024)

// ---- flatbuffer --------------------------------------------------------------
alignas(16) static const unsigned char g_fall_model_tflite[] = {{
{c_bytes(tfl)}
}};
static const unsigned int g_fall_model_tflite_len = {len(tfl)};

// ---- boot self-test vectors (already quantized, row-major [sample][channel]) --
static const int8_t g_fall_selftest_fall[FALL_MODEL_WINDOW_SAMPLES * FALL_MODEL_CHANNELS] = {{
{c_int8(quant(st['fall']))}
}};
static const int8_t g_fall_selftest_adl[FALL_MODEL_WINDOW_SAMPLES * FALL_MODEL_CHANNELS] = {{
{c_int8(quant(st['adl']))}
}};
"""
    HEADER.parent.mkdir(parents=True, exist_ok=True)
    HEADER.write_text(header)
    print(f"[export] wrote {HEADER} ({len(tfl)} model bytes, header {HEADER.stat().st_size / 1024:.1f} KiB)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
